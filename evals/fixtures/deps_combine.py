"""tiny_app plus a pip lock script and two Dependabot branches, for the stub-graded deps-combine task.

`main` holds `requirements.in`, its lockfile `requirements.lock` (written by `tools/lock.py`) and
`tools/requirements.in`. Two bot branches bump `alpha` (root) and `gamma` (tools); main then moves on (`delta`).
The expected end state is one combined branch with `alpha==2.0.0` and `delta==1.0.0`, its lockfile regenerated
by the lock command, and `gamma==2.0.0` left out. No network, no real names: the bot identity is GitHub's
public Dependabot one, and the commits carry the fixture's fixed dates.
"""
from __future__ import annotations

import os
import subprocess
from pathlib import Path

from . import commit_all, init_repo, tiny_app, write_files
from evals.harness.common import git

LOCK_SOURCE = '''\
import hashlib
import pathlib


def lock_text(text):
    digest = hashlib.sha256(text.encode()).hexdigest()
    lines = sorted(line for line in text.splitlines() if line)
    return "# generated by tools/lock.py from requirements.in sha256 " + digest + "\\n" + "".join(line + "\\n" for line in lines)


if __name__ == "__main__":
    src = pathlib.Path("requirements.in").read_text()
    pathlib.Path("requirements.lock").write_text(lock_text(src))
'''

_ns: dict = {}
exec(LOCK_SOURCE, _ns)  # the same source as tools/lock.py, so expected content cannot drift from the script
lock_text = _ns["lock_text"]

PROFILE = tiny_app.PROFILE + """
deps:
  cooldown_days: 3
  time_budget_minutes: 90
  lock_freshness:
    - when: ["requirements.in"]
      run: "python3 tools/lock.py"
      lockfiles: ["requirements.lock"]
"""

BOT_NAME = "dependabot[bot]"
BOT_EMAIL = "49699333+dependabot[bot]@users.noreply.github.com"
DATE = "2026-01-01T00:00:00Z"

MAIN_IN = "alpha==1.0.0\ngamma==1.0.0\n"
FINAL_IN = "alpha==2.0.0\ngamma==1.0.0\ndelta==1.0.0\n"


def _bot_commit(dest: Path, message: str) -> None:
    """A commit with Dependabot's identity (the git() helper cannot override its identity)."""
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": str(dest), "GIT_CONFIG_NOSYSTEM": "1",
           "GIT_COMMITTER_NAME": "GitHub", "GIT_COMMITTER_EMAIL": "noreply@github.com",
           "GIT_AUTHOR_DATE": DATE, "GIT_COMMITTER_DATE": DATE}
    subprocess.run(["git", "add", "-A"], cwd=dest, check=True, env=env)
    subprocess.run(["git", "commit", "-q", "-m", message, "--author", f"{BOT_NAME} <{BOT_EMAIL}>"],
                   cwd=dest, check=True, env=env, capture_output=True)


def build(dest: Path, **params) -> dict:
    init_repo(dest, {**tiny_app.FILES, ".tld/toolkit.yaml": PROFILE, "tools/lock.py": LOCK_SOURCE,
                     "requirements.in": MAIN_IN, "requirements.lock": lock_text(MAIN_IN),
                     "tools/requirements.in": "gamma==1.0.0\n"})
    git("checkout", "-q", "-b", "dependabot/pip/alpha-2.0.0", cwd=dest)
    bumped = MAIN_IN.replace("alpha==1.0.0", "alpha==2.0.0")
    write_files(dest, {"requirements.in": bumped, "requirements.lock": lock_text(bumped)})
    _bot_commit(dest, "Bump alpha from 1.0.0 to 2.0.0")
    git("checkout", "-q", "main", cwd=dest)
    git("checkout", "-q", "-b", "dependabot/pip/tools/gamma-2.0.0", cwd=dest)
    write_files(dest, {"tools/requirements.in": "gamma==2.0.0\n"})
    _bot_commit(dest, "Bump gamma from 1.0.0 to 2.0.0 in /tools")
    git("checkout", "-q", "main", cwd=dest)
    write_files(dest, {"requirements.in": MAIN_IN + "delta==1.0.0\n", "requirements.lock": lock_text(MAIN_IN + "delta==1.0.0\n")})
    commit_all(dest, "Add delta")
    return {
        "main_branch": "main",
        "protected_refs": {
            "origin/main": git("rev-parse", "main", cwd=dest).strip(),
            "origin/dependabot/pip/alpha-2.0.0": git("rev-parse", "dependabot/pip/alpha-2.0.0", cwd=dest).strip(),
            "origin/dependabot/pip/tools/gamma-2.0.0": git("rev-parse", "dependabot/pip/tools/gamma-2.0.0", cwd=dest).strip(),
        },
        "bot_prs": [11, 12],
        "branch_files": {"equals": {"requirements.in": FINAL_IN, "requirements.lock": lock_text(FINAL_IN)},
                         "absent": ["gamma==2.0.0"]},
        "left_out": "#12",
    }
