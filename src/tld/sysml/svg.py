"""The architecture picture as SVG, drawn from a `tld.sysml.layout.Layout` (3.5 of the plan, docs/guides/sysml.md).

Pure and byte-stable: integer coordinates, one element per line, `\\n` line ends, no clock. Only the elements and
attributes of the allowlists below are written; every text node and attribute value is XML-escaped; the text is
names, types and counts only, never doc text. Python 3.11+, stdlib only.
"""
from __future__ import annotations

import re

from tld.sysml.layout import Box, Edge, Frame, Layout
from tld.sysml.types import ModelError

STAMP = "<!-- generated by tld ops sysml render, layout 1; do not edit -->"
ELEMENTS = frozenset({"svg", "g", "rect", "line", "polygon", "text", "title"})
ATTRIBUTES = frozenset({
    "xmlns", "width", "height", "viewBox", "role", "aria-label", "x", "y", "x1", "y1", "x2", "y2", "points",
    "fill", "stroke", "stroke-width", "stroke-dasharray", "font-family", "font-size", "text-anchor",
})
BACKGROUND = "#ffffff"
FRAME_STROKE = "#8b949e"
BOX_FILL = "#f6f8fa"
INK = "#1f2328"
_STAMP_RE = re.compile(r"^<!-- generated by tld ops sysml render, layout ([0-9]{1,9}); do not edit -->$", re.M)


_XML_BAD = re.compile("[^\t\n\r\u0020-\ud7ff\ue000-\ufffd\U00010000-\U0010ffff]")


def esc(text: str) -> str:
    """XML-escape `&`, `<`, `>` and `"` (the only characters that can end a text node or an attribute).

    Raises ModelError for a code point that XML 1.0 does not allow, so the file is never not well-formed."""
    if _XML_BAD.search(text):
        raise ModelError("cannot draw a character that XML 1.0 does not allow")
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def layout_number(text: str) -> int | None:
    """The layout number of the stamp line of an existing output, None when there is no stamp."""
    m = _STAMP_RE.search(text)
    return int(m.group(1)) if m else None


def _text(x: int, y: int, value: str, anchor: str = "") -> str:
    extra = f' text-anchor="{anchor}"' if anchor else ""
    return (f'<text x="{int(x)}" y="{int(y)}" fill="{INK}" font-family="monospace" font-size="12"{extra}>'
            f"{esc(value)}</text>")


def _frame(f: Frame) -> list[str]:
    return [
        f'<rect x="{int(f.x)}" y="{int(f.y)}" width="{int(f.w)}" height="{int(f.h)}" fill="none" '
        f'stroke="{FRAME_STROKE}" stroke-width="1"/>',
        _text(f.x + 8, f.y + 18, f.title),
    ]


def _edge(e: Edge) -> list[str]:
    dash = ' stroke-dasharray="6 4"' if e.kind == "dependency" else ""
    out = [f'<line x1="{int(e.x1)}" y1="{int(e.y1)}" x2="{int(e.x2)}" y2="{int(e.y2)}" stroke="{INK}" '
           f'stroke-width="1"{dash}/>']
    if e.head:
        pts = " ".join(f"{int(e.head[i])},{int(e.head[i + 1])}" for i in range(0, len(e.head) - 1, 2))
        fill = INK if e.kind == "dependency" else BACKGROUND
        out.append(f'<polygon points="{pts}" fill="{fill}" stroke="{INK}" stroke-width="1"/>')
    if e.label:
        out.append(_text(round((e.x1 + e.x2) / 2), round((e.y1 + e.y2) / 2) - 4, e.label, "middle"))
    return out


def _box(b: Box) -> list[str]:
    out = [f'<rect x="{int(b.x)}" y="{int(b.y)}" width="{int(b.w)}" height="{int(b.h)}" fill="{BOX_FILL}" '
           f'stroke="{INK}" stroke-width="1"/>']
    out += [_text(t.x, t.y, t.value) for t in b.texts]
    return out


def to_svg(lay: Layout) -> str:
    """The SVG of `lay`: the stamp line, then the root element; edges are drawn before boxes."""
    n_defs, n_pkgs = lay.counts[0], lay.counts[1]
    label = f"Architecture diagram: {n_defs} part defs in {n_pkgs} packages"
    w, h = int(lay.width), int(lay.height)
    lines = [
        STAMP,
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" '
        f'aria-label="{esc(label)}">',
        "<title>Architecture model</title>",
        f'<rect x="0" y="0" width="{w}" height="{h}" fill="{BACKGROUND}"/>',
    ]
    for f in lay.frames:
        lines += _frame(f)
    for e in lay.edges:
        lines += _edge(e)
    for b in lay.boxes:
        lines += _box(b)
    lines.append("</svg>")
    return "\n".join(lines) + "\n"
