"""The sysml playbook, its command file and the stop message its eval expects."""
from __future__ import annotations

import re

from conftest import ROOT, CLAUDE, _load

PLAYBOOK = ROOT / "playbooks" / "sysml.md"
STEPS = ("1. Survey", "2. Confirm", "3. Draft", "4. Validate and draw", "5. Deliver")
STOPS = (
    "toolkit.yaml: missing required key 'sysml.subset' (add a sysml block; see docs/guides/sysml.md)",
    "The working tree has changes; commit or stash them first. Nothing was changed.",
    "The architecture model already exists (sysml/model holds files); plans update it. Nothing was changed.",
    "docs/architecture.md or docs/architecture.svg exists and was not generated by tld; move it first. Nothing was changed.",
    "The component list is not valid. Nothing was changed.",
    "Usage: sysml [check | init]",
)


def test_playbook_has_usage_record_and_the_five_steps():
    text = PLAYBOOK.read_text()
    assert "\nUsage: sysml [check | init]\n" in text
    assert "attended: true" in text
    headings = [l[4:] for l in text.splitlines() if l.startswith("### ")]
    assert headings == list(STEPS)


def test_command_file_names_the_playbook_path():
    text = (CLAUDE / "commands" / "sysml.md").read_text()
    assert "${CLAUDE_PLUGIN_ROOT}/playbooks/sysml.md" in text
    assert len(text.encode()) < 1500


def test_sysml_playbook_names_the_stop_message_of_its_eval(tmp_path, capsys):
    text = (ROOT / "evals" / "fixtures" / "commands.py").read_text()
    m = re.search(r'command == "sysml":.*?expected\["stop_message"\] = "([^"]+)"', text, re.S)
    assert m, "no sysml stop_message in evals/fixtures/commands.py"
    message = m.group(1)
    assert message in PLAYBOOK.read_text()
    profile = tmp_path / "toolkit.yaml"
    profile.write_text("tld:\n  version: '>=1.0'\n")
    assert _load("tld.ops.sysml").main(["check", "--profile", str(profile), "--root", str(tmp_path)]) == 2
    assert capsys.readouterr().err.strip() == message


def test_playbook_contains_each_stop_message_of_the_design():
    text = " ".join(PLAYBOOK.read_text().split())
    for message in STOPS:
        assert message in text, message


def test_sysml_init_stops_on_a_dirty_tree_before_it_branches():
    text = PLAYBOOK.read_text()
    msg = "The working tree has changes; commit or stash them first. Nothing was changed."
    assert msg in " ".join(text.split())
    assert text.index("git status --porcelain") < text.index("git checkout -b chore/sysml-init-")


def test_playbook_never_merges_and_uses_only_real_subcommands():
    text = PLAYBOOK.read_text()
    assert "Merge, approve or enable auto-merge" in text
    used = set(re.findall(r"tld ops sysml (?:(?:--\S+ )*)([a-z-]+)", text))
    assert used <= {"check", "render", "new-change", "archive"}, used
    for call in re.findall(r"`(tld ops sysml [^`]+)`", text):
        assert "--profile .tld/toolkit.yaml" in call, call
